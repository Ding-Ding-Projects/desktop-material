#!/usr/bin/env node
// Regenerate `app/styles/material/_standalone-roles.scss` from the application's
// own token layer.
//
// The crash reporter, the quick-action panel and the internal browser are
// separate renderers with their own bundles. They cannot share the main token
// layer's theming, which switches on `body.theme-dark` — a class the
// application sets from its settings, and one a crashed or standalone renderer
// has no access to. They follow the operating system preference instead.
//
// So the role NAMES are shared and the VALUES are copied here. The duplication
// is structural and cannot be removed; what can be removed is the chance of the
// copies drifting apart, which is why this is a script rather than a thing
// somebody retypes, and why `standalone-window-roles-test.ts` asserts the two
// still agree.
//
// Usage:
//   node script/generate-standalone-roles.mjs           # write
//   node script/generate-standalone-roles.mjs --check   # fail if it would change

import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const materialPath = join(root, 'app', 'styles', '_material.scss')
const outputPath = join(
  root,
  'app',
  'styles',
  'material',
  '_standalone-roles.scss'
)

const Accents = ['violet', 'teal', 'green', 'amber', 'rose']

function stripComments(text) {
  return text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '')
}

/** The text of one top-level block, or null when the selector is absent. */
function blockFor(source, selector) {
  const opener = `${selector} {`
  const start = source.indexOf(opener)
  if (start === -1) {
    return null
  }
  const end = source.indexOf('\n}', start)
  return source.slice(start, end)
}

function declarations(source, selector, prefix) {
  const block = blockFor(source, selector)
  if (block === null) {
    return []
  }
  const pattern = new RegExp(`(${prefix}[a-z0-9-]+)\\s*:\\s*([^;]+);`, 'g')
  return [...block.matchAll(pattern)].map(match => [match[1], match[2].trim()])
}

function emit(pairs) {
  return pairs.map(([name, value]) => `  ${name}: ${value};`).join('\n')
}

function build() {
  const source = stripComments(readFileSync(materialPath, 'utf8'))

  const light = declarations(source, ':root', '--md-sys-color-')
  const dark = declarations(source, 'body.theme-dark', '--md-sys-color-')
  const shape = declarations(source, ':root', '--md-sys-shape-corner-')

  // A generator that silently produces an empty mixin would hand every
  // standalone window a stylesheet with no roles in it, and the comparison test
  // would then pass by comparing nothing against nothing.
  if (light.length < 20 || dark.length < 20 || shape.length < 4) {
    throw new Error(
      `parsed ${light.length} light, ${dark.length} dark and ${shape.length} ` +
        'shape declarations out of _material.scss; the parser has drifted from ' +
        'the file it reads'
    )
  }

  const parts = [
    `// GENERATED by script/generate-standalone-roles.mjs — do not edit by hand.
//
// Material Design 3 roles for the standalone windows: the crash reporter, the
// quick-action panel and the internal browser. Each previously carried a private
// palette on a different hue from the application's own, so three surfaces the
// user reaches from inside the product did not look like the product.
//
// These windows cannot share the main token layer's theming, which switches on
// \`body.theme-dark\`; they read the operating system preference instead, which
// is the only signal a standalone renderer has. The values are copied from
// \`app/styles/_material.scss\` and \`standalone-window-roles-test.ts\` asserts
// they still match, so drift between the copies fails closed.

@mixin md-standalone-color-roles-light {
${emit(light)}
}

@mixin md-standalone-color-roles-dark {
${emit(dark)}
}

@mixin md-standalone-shape-roles {
${emit(shape)}
}

// Included once by a window that follows the operating system preference.
@mixin md-standalone-roles {
  :root {
    @include md-standalone-color-roles-light;
    @include md-standalone-shape-roles;
  }

  @media (prefers-color-scheme: dark) {
    :root {
      @include md-standalone-color-roles-dark;
    }
  }
}

// Accent variants, mirroring the application's own \`data-dm-accent\` feature.
// The internal browser previously carried its own values under the same names,
// so one accent rendered two different colours depending on which window the
// user happened to be looking at.
`,
  ]

  for (const accent of Accents) {
    const accentLight = declarations(
      source,
      `body[data-dm-accent='${accent}']`,
      '--md-sys-color-'
    )
    const accentDark = declarations(
      source,
      `body.theme-dark[data-dm-accent='${accent}']`,
      '--md-sys-color-'
    )

    if (accentLight.length === 0 || accentDark.length === 0) {
      throw new Error(
        `accent "${accent}" has no light or dark declarations in ` +
          '_material.scss; either it was renamed or the accent list here is stale'
      )
    }

    parts.push(`
@mixin md-standalone-accent-${accent}-light {
${emit(accentLight)}
}

@mixin md-standalone-accent-${accent}-dark {
${emit(accentDark)}
}
`)
  }

  return parts.join('')
}

const generated = build()
const checking = process.argv.includes('--check')

if (checking) {
  const current = readFileSync(outputPath, 'utf8')
  if (current !== generated) {
    console.error(
      'app/styles/material/_standalone-roles.scss is out of date. Run:\n' +
        '  node script/generate-standalone-roles.mjs'
    )
    process.exit(1)
  }
  console.log('_standalone-roles.scss is up to date')
} else {
  writeFileSync(outputPath, generated)
  console.log(`wrote ${outputPath}`)
}
